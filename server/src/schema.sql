-- PulseFit schema. Safe to run repeatedly (npm run migrate).
--
-- In plain English:
--   coaches        the people who teach. Each has a bio, a quote and a photo.
--   classes        one row per weekly slot (day, morning/evening, time). Every
--                  class is taught by exactly one coach.
--   plans          the membership tiers and their price in cents.
--   saved_classes  which signed-in user saved which class. A user can save many
--                  classes and a class can be saved by many users, so this is a
--                  join table keyed on the pair.
--   user, session, account, verification
--                  owned by Better Auth. "user" is a person, "account" holds
--                  their hashed password, "session" is one signed-in browser.

CREATE TABLE IF NOT EXISTS coaches (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        text NOT NULL,
    initials    text NOT NULL,
    specialty   text NOT NULL,
    bio         text NOT NULL,
    quote       text NOT NULL,
    image       text NOT NULL,
    image_alt   text NOT NULL,
    credit      text NOT NULL
);

CREATE TABLE IF NOT EXISTS classes (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    day         text NOT NULL CHECK (day IN ('Mon','Tue','Wed','Thu','Fri','Sat')),
    period      text NOT NULL CHECK (period IN ('morning','evening')),
    time        text NOT NULL,
    name        text NOT NULL,
    level       text NOT NULL CHECK (level IN ('gentle','steady','hard')),
    coach_id    integer NOT NULL REFERENCES coaches(id),
    UNIQUE (day, period)
);

CREATE TABLE IF NOT EXISTS plans (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        text NOT NULL,
    price_cents integer NOT NULL CHECK (price_cents >= 0),
    per         text NOT NULL,
    note        text NOT NULL,
    perks       text[] NOT NULL,
    cta         text NOT NULL,
    featured    boolean NOT NULL DEFAULT false,
    position    integer NOT NULL
);

CREATE TABLE IF NOT EXISTS "user" (
    id              text PRIMARY KEY,
    name            text NOT NULL,
    email           text NOT NULL UNIQUE,
    "emailVerified" boolean NOT NULL,
    image           text,
    "createdAt"     timestamptz NOT NULL,
    "updatedAt"     timestamptz NOT NULL
);

CREATE TABLE IF NOT EXISTS session (
    id          text PRIMARY KEY,
    "expiresAt" timestamptz NOT NULL,
    token       text NOT NULL UNIQUE,
    "createdAt" timestamptz NOT NULL,
    "updatedAt" timestamptz NOT NULL,
    "ipAddress" text,
    "userAgent" text,
    "userId"    text NOT NULL REFERENCES "user"(id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS session_user_id_idx ON session ("userId");

CREATE TABLE IF NOT EXISTS account (
    id                        text PRIMARY KEY,
    "accountId"               text NOT NULL,
    "providerId"              text NOT NULL,
    "userId"                  text NOT NULL REFERENCES "user"(id) ON DELETE CASCADE,
    "accessToken"             text,
    "refreshToken"            text,
    "idToken"                 text,
    "accessTokenExpiresAt"    timestamptz,
    "refreshTokenExpiresAt"   timestamptz,
    scope                     text,
    password                  text,
    "createdAt"               timestamptz NOT NULL,
    "updatedAt"               timestamptz NOT NULL
);
CREATE INDEX IF NOT EXISTS account_user_id_idx ON account ("userId");

CREATE TABLE IF NOT EXISTS verification (
    id          text PRIMARY KEY,
    identifier  text NOT NULL,
    value       text NOT NULL,
    "expiresAt" timestamptz NOT NULL,
    "createdAt" timestamptz,
    "updatedAt" timestamptz
);

CREATE TABLE IF NOT EXISTS saved_classes (
    user_id     text    NOT NULL REFERENCES "user"(id) ON DELETE CASCADE,
    class_id    integer NOT NULL REFERENCES classes(id) ON DELETE CASCADE,
    saved_at    timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, class_id)
);
