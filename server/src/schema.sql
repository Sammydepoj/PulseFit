-- PulseFit schema. Safe to run repeatedly (npm run migrate).
--
-- In plain English:
--   coaches        the people who teach. Each has a bio, a quote and a photo.
--   classes        one row per weekly slot (day, morning/evening, time). Every
--                  class is taught by exactly one coach.
--   plans          the membership tiers and their price in cents.
--   users          one row per person. Passwords are stored as a salted scrypt
--                  hash, never in plain text. Email is unique.
--   sessions       one row per signed-in browser. The cookie holds a random
--                  token; only its SHA-256 hash is stored here.
--   orders         one row per purchase attempt, tied to the user who made it.
--                  Starts as 'pending'; only Stripe's webhook may set it to 'paid'.
--   order_items    what an order contains: the plan, its name and the price it
--                  had at the time, copied here so later price changes never
--                  rewrite past orders.
--   saved_classes  which user saved which class. A user can save many classes
--                  and a class can be saved by many users, so this is a join
--                  table keyed on the pair.

-- One-time cleanup: the app used to keep accounts in a third-party library's
-- tables. If they are still here, drop them (and the saved_classes rows that
-- pointed at them) so the tables below can replace them. Does nothing once gone.
DO $$
BEGIN
    IF to_regclass('"user"') IS NOT NULL THEN
        DROP TABLE IF EXISTS saved_classes, verification, account, session, "user" CASCADE;
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS coaches (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        text NOT NULL,
    initials    text NOT NULL,
    specialty   text NOT NULL,
    bio         text NOT NULL,
    quote       text NOT NULL,
    image       text NOT NULL,
    image_alt   text NOT NULL,
    credit      text NOT NULL
);

CREATE TABLE IF NOT EXISTS classes (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    day         text NOT NULL CHECK (day IN ('Mon','Tue','Wed','Thu','Fri','Sat')),
    period      text NOT NULL CHECK (period IN ('morning','evening')),
    time        text NOT NULL,
    name        text NOT NULL,
    level       text NOT NULL CHECK (level IN ('gentle','steady','hard')),
    coach_id    integer NOT NULL REFERENCES coaches(id),
    UNIQUE (day, period)
);

CREATE TABLE IF NOT EXISTS plans (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        text NOT NULL,
    price_cents integer NOT NULL CHECK (price_cents >= 0),
    per         text NOT NULL,
    note        text NOT NULL,
    perks       text[] NOT NULL,
    cta         text NOT NULL,
    featured    boolean NOT NULL DEFAULT false,
    position    integer NOT NULL
);

CREATE TABLE IF NOT EXISTS users (
    id            uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    name          text NOT NULL,
    email         text NOT NULL UNIQUE CHECK (email = lower(email)),
    password_hash text NOT NULL,
    created_at    timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS sessions (
    token_hash  text PRIMARY KEY,
    user_id     uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    expires_at  timestamptz NOT NULL,
    created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS sessions_user_id_idx ON sessions (user_id);

CREATE TABLE IF NOT EXISTS saved_classes (
    user_id     uuid    NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    class_id    integer NOT NULL REFERENCES classes(id) ON DELETE CASCADE,
    saved_at    timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, class_id)
);

CREATE TABLE IF NOT EXISTS orders (
    id                        uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id                   uuid NOT NULL REFERENCES users(id),
    status                    text NOT NULL DEFAULT 'pending'
                              CHECK (status IN ('pending', 'paid', 'expired')),
    total_cents               integer NOT NULL CHECK (total_cents >= 0),
    currency                  text NOT NULL DEFAULT 'usd',
    stripe_session_id         text UNIQUE,
    stripe_payment_intent_id  text,
    created_at                timestamptz NOT NULL DEFAULT now(),
    paid_at                   timestamptz
);
CREATE INDEX IF NOT EXISTS orders_user_id_idx ON orders (user_id);

CREATE TABLE IF NOT EXISTS order_items (
    id                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id          uuid NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    plan_id           integer NOT NULL REFERENCES plans(id),
    plan_name         text NOT NULL,
    unit_price_cents  integer NOT NULL CHECK (unit_price_cents >= 0),
    quantity          integer NOT NULL DEFAULT 1 CHECK (quantity > 0)
);
CREATE INDEX IF NOT EXISTS order_items_order_id_idx ON order_items (order_id);
